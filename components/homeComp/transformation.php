<!-- Physics-based LERP Smooth Scroll Engine -->
<script>
  (function () {
    const container = document.getElementById("transformation-scroll-container");
    const card2 = document.getElementById("scroll-card-2");
    const card3 = document.getElementById("scroll-card-3");
    const card4 = document.getElementById("scroll-card-4");

    if (!container) return;

    let targetProgress = 0;
    let currentProgress = 0;
    let isAnimating = false;

    function calcTargetProgress() {
      if (window.innerWidth < 1024) {
        return 0;
      }
      const rect = container.getBoundingClientRect();
      const totalScrollable = container.offsetHeight - window.innerHeight;
      if (totalScrollable <= 0) return 0;

      const scrolled = -rect.top;
      return Math.min(Math.max(scrolled / totalScrollable, 0), 1);
    }

    // Smoothstep cubic easing: 3x^2 - 2x^3
    function smoothstep(t) {
      return t * t * (3 - 2 * t);
    }

    function renderLoop() {
      if (window.innerWidth < 1024) {
        if (card2) { card2.style.transform = "none"; card2.style.opacity = "1"; }
        if (card3) { card3.style.transform = "none"; card3.style.opacity = "1"; }
        if (card4) { card4.style.transform = "none"; card4.style.opacity = "1"; }
        isAnimating = false;
        return;
      }

      // Physics damping interpolation (Faster & responsive LERP factor)
      const diff = targetProgress - currentProgress;
      currentProgress += diff * 0.14;

      if (Math.abs(diff) < 0.0003) {
        currentProgress = targetProgress;
      }

      // Card 2 Glide (starts at 0.03, reaches top at 0.38)
      const p2 = Math.min(Math.max((currentProgress - 0.03) / 0.35, 0), 1);
      const e2 = smoothstep(p2);
      const y2 = (1 - e2) * 140;
      const op2 = 0.30 + (e2 * 0.70);
      if (card2) {
        card2.style.transform = `translate3d(0, ${y2.toFixed(2)}px, 0)`;
        card2.style.opacity = op2.toFixed(3);
      }

      // Card 3 Glide (starts at 0.18, reaches top at 0.62)
      const p3 = Math.min(Math.max((currentProgress - 0.18) / 0.44, 0), 1);
      const e3 = smoothstep(p3);
      const y3 = (1 - e3) * 240;
      const op3 = 0.20 + (e3 * 0.80);
      if (card3) {
        card3.style.transform = `translate3d(0, ${y3.toFixed(2)}px, 0)`;
        card3.style.opacity = op3.toFixed(3);
      }

      // Card 4 Glide (starts at 0.36, reaches top at 0.85)
      const p4 = Math.min(Math.max((currentProgress - 0.36) / 0.49, 0), 1);
      const e4 = smoothstep(p4);
      const y4 = (1 - e4) * 340;
      const op4 = 0.10 + (e4 * 0.90);
      if (card4) {
        card4.style.transform = `translate3d(0, ${y4.toFixed(2)}px, 0)`;
        card4.style.opacity = op4.toFixed(3);
      }

      if (Math.abs(targetProgress - currentProgress) > 0.0003) {
        requestAnimationFrame(renderLoop);
      } else {
        isAnimating = false;
      }
    }

    function onScrollOrResize() {
      targetProgress = calcTargetProgress();
      if (!isAnimating) {
        isAnimating = true;
        requestAnimationFrame(renderLoop);
      }
    }

    window.addEventListener("scroll", onScrollOrResize, { passive: true });
    window.addEventListener("resize", onScrollOrResize, { passive: true });

    if (window.lenis) {
      window.lenis.on('scroll', onScrollOrResize);
    }

    document.addEventListener("DOMContentLoaded", () => {
      targetProgress = calcTargetProgress();
      currentProgress = targetProgress;
      if (window.lenis) {
        window.lenis.on('scroll', onScrollOrResize);
      }
      onScrollOrResize();
    });

    setTimeout(() => {
      targetProgress = calcTargetProgress();
      currentProgress = targetProgress;
      if (window.lenis) {
        window.lenis.on('scroll', onScrollOrResize);
      }
      onScrollOrResize();
    }, 200);
  })();
</script>
